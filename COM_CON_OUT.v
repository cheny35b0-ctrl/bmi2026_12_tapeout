//COM_CON_OUT for multi device + new 10bit ADC

module COM_CON_OUT(
   input CLK,POR,S_Bias_OPT,S_Bias_ELE,OPERATE_OPT,OPERATE_ELE,
   input [9:0] DATA_OPT,DATA_ELE,
   input [7:0] ADDRESS,
   output COM_EN_OPT, COM_EN_ELE,
   output OUT
);

wire [1:0] MEASUREMENT_CODE;
wire [19:0] DATA;

assign DATA = {DATA_OPT, DATA_ELE};

localparam OPT_DELAY = 10'd000, ELE_DELAY = 10'd250;
localparam TYPE_OPT = 1'b0, TYPE_ELE = 1'b1;

wire ENABLE_WIRE;

COM_CON_TOP COM_CON_TOP(
.CLK(CLK),
.POR(POR),
.ADC_STATE(S_Bias_OPT || S_Bias_ELE),
.DATA(DATA),
.OPERATE(MEASUREMENT_CODE),
.TYPE(MEASUREMENT_CODE),
.ADDRESS(ADDRESS[7:0]),
.OPT_DELAY(OPT_DELAY),
.ELE_DELAY(ELE_DELAY),
.ENABLE(ENABLE_WIRE),
.OUT(OUT)
);

assign COM_EN_OPT = ENABLE_WIRE;
assign COM_EN_ELE = ENABLE_WIRE;

MEASUREMENT_TYPE_ENCODER MEASUREMENT_TYPE_ENCODER(
.CLK(CLK),
.POR(POR),
.OPERATE_OPT(OPERATE_OPT),
.OPERATE_ELE(OPERATE_ELE),
.OUT(MEASUREMENT_CODE)
);

endmodule
